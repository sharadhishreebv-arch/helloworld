
public class New
{

	public static void main(String[] args)
	{
	  int a=20;
	  int b=10;
	  System.out.println("===relational operators===");
	  System.out.println("a==b:"+(a==b));
	  System.out.println("a!=b:"+(a!=b));
	  System.out.println("a>b:"+(a>b));
	  System.out.println("a<b:"+(a<b));
	  System.out.println("a>=b:"+(a>=b));
	  System.out.println("a<=b:"+(a<=b));
	  System.out.println("===logical operators===");
	  boolean x=true;
	  boolean y=false;
	  System.out.println("x&&y;"+(x&&y));
	  System.out.println("x||y"+(x||y));
	  System.out.println("!x:"+(!x));
	  }

}
